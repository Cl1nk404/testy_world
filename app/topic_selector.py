from datetime import date

SEASON_TOPICS = {
    "winter": [
        "густой чечевичный суп", "запечённая картошка с травами",
        "горячий пряный шоколад", "яблочный крамбл", "овощное рагу"
    ],
    "spring": [
        "зелёный омлет с травами", "лимонный пирог", "салат с редисом",
        "лёгкий овощной суп", "творожные сырники"
    ],
    "summer": [
        "холодный ягодный напиток", "томатная брускетта", "персиковый крамбл",
        "летний салат с огурцами", "домашний лимонад"
    ],
    "autumn": [
        "тыквенный суп-пюре", "грушевый пирог", "грибное ризотто",
        "запечённые корнеплоды", "пряное яблочное печенье"
    ],
}

def season_for_month(month: int) -> str:
    # Северное полушарие; при необходимости позже добавим настройку региона.
    if month in (12, 1, 2):
        return "зима"
    if month in (3, 4, 5):
        return "весна"
    if month in (6, 7, 8):
        return "лето"
    return "осень"

def candidates_for_date(day: date):
    key = { "зима": "winter", "весна": "spring", "лето": "summer", "осень": "autumn" }[season_for_month(day.month)]
    return season_for_month(day.month), SEASON_TOPICS[key]
